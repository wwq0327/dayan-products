  getByCategory(categoryId) {
    if (!categoryId || categoryId === 'all') return this.materials;
    return this.materials.filter(m => m.category === categoryId);
  },

  getById(id) {
    return this.materials.find(m => m.id === id) || null;
  },

  getCategoryStats() {
    const stats = {};
    this.categories.forEach(c => { stats[c.id] = 0; });
    this.materials.forEach(m => { stats[m.category] = (stats[m.category] || 0) + 1; });
    return stats;
  },

  getCategoryName(id) {
    const cat = this.categories.find(c => c.id === id);
    return cat ? cat.name : '未分类';
  },

  getAdjacent(currentId) {
    const filtered = this._currentFiltered || this.materials;
    const idx = filtered.findIndex(m => m.id === currentId);
    return {
      prev: idx > 0 ? filtered[idx - 1] : null,
      next: idx < filtered.length - 1 ? filtered[idx + 1] : null,
    };
  },
